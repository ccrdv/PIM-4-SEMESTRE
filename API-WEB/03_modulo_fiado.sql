-- 1. tbl_Modulo: lista de modulos e se estao ligados (S/N).
--    A API liga/desliga pelo PUT /api/Modulos/{nome}
CREATE TABLE "PIM"."tbl_Modulo" (
  "Nome_Modulo"      NVARCHAR2(50)  NOT NULL,
  "Descricao_Modulo" NVARCHAR2(200),
  "Ativo_Modulo"     NVARCHAR2(1)  DEFAULT N'S' NOT NULL,
  CONSTRAINT "PK_tbl_Modulo" PRIMARY KEY ("Nome_Modulo"),
  CONSTRAINT "CK_tbl_Modulo_Ativo" CHECK ("Ativo_Modulo" IN (N'S', N'N'))
);

INSERT INTO "PIM"."tbl_Modulo" ("Nome_Modulo", "Descricao_Modulo", "Ativo_Modulo")
VALUES (N'fiado', N'Vendas a prazo (fiado) e recebimento dos pagamentos', N'S');

-- 2. tbl_Fiado: uma linha para cada venda feita no fiado.
--    O saldo NAO fica gravado: e Valor_Original menos a soma dos pagamentos
--    da venda em tbl_Forma_Pagamento (assim o recibo e o comprovante continuam funcionando).
CREATE TABLE "PIM"."tbl_Fiado" (
  "Id_Fiado"       NUMBER(10,0) GENERATED BY DEFAULT ON NULL AS IDENTITY,
  "Id_Venda"       NUMBER(10,0) NOT NULL,
  "Id_Pessoa"      NUMBER(10,0) NOT NULL,
  "Valor_Original" NUMBER(12,2) NOT NULL,
  "Data_Hora_Fiado" TIMESTAMP(7) DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT "PK_tbl_Fiado" PRIMARY KEY ("Id_Fiado"),
  CONSTRAINT "UQ_tbl_Fiado_Venda" UNIQUE ("Id_Venda"),
  CONSTRAINT "FK_tbl_Fiado_tbl_Venda"  FOREIGN KEY ("Id_Venda")  REFERENCES "PIM"."tbl_Venda" ("Id_Venda"),
  CONSTRAINT "FK_tbl_Fiado_tbl_Pessoa" FOREIGN KEY ("Id_Pessoa") REFERENCES "PIM"."tbl_Pessoa" ("Id_Pessoa")
);

CREATE INDEX "IX_tbl_Fiado_Pessoa" ON "PIM"."tbl_Fiado" ("Id_Pessoa");

