-- =====================================================================
-- SistemaWhiteLabel - RENUMERA os produtos: ids 1, 2, 3, 4 e 5, na ordem da lista abaixo,
-- e o proximo produto cadastrado sera o 6. Rode conectado como PIM.
--
-- Como as vendas e compras ja gravadas apontam para o id do produto, o script nao apaga os produtos:
-- ele troca o id do produto e, junto, o id nas tabelas que apontam para ele (tb_item_venda, tb_item_compra).
-- O resultado e o mesmo de apagar e cadastrar de novo, sem perder o historico.
-- Se a tabela tiver algum produto fora da lista, o script para e nao muda nada.
-- Para mudar a numeracao, mude a ordem das linhas em v_nomes (e o NOT IN logo abaixo).
-- =====================================================================
SET DEFINE OFF;
SET SERVEROUTPUT ON;

DECLARE
  TYPE t_nomes IS VARRAY(5) OF NVARCHAR2(100);
  TYPE t_txt   IS TABLE OF VARCHAR2(200);
  v_nomes t_nomes := t_nomes(N'Coca-Cola Lata', N'Guaraná lata', N'guarita lata', N'Fanta laranja lata', N'Fanta uva lata');
  v_case  VARCHAR2(1000);
  v_old   NUMBER;
  v_n     NUMBER;
  v_pk    VARCHAR2(128);
  v_tab   t_txt;
  v_cons  t_txt;
  v_col   t_txt;
  v_off   BOOLEAN := FALSE;

  PROCEDURE religa IS
  BEGIN
    IF v_cons IS NOT NULL THEN
      FOR i IN 1 .. v_cons.COUNT LOOP
        BEGIN
          EXECUTE IMMEDIATE 'ALTER TABLE "PIM"."' || v_tab(i) || '" ENABLE CONSTRAINT "' || v_cons(i) || '"';
        EXCEPTION WHEN OTHERS THEN
          DBMS_OUTPUT.PUT_LINE('ATENCAO: nao consegui religar ' || v_cons(i) || ': ' || SQLERRM);
        END;
      END LOOP;
    END IF;
    v_off := FALSE;
  END;
BEGIN
  -- 1. so produtos da lista
  SELECT COUNT(*) INTO v_n FROM "PIM"."tb_produto"
   WHERE "descricao_produto" NOT IN (N'Coca-Cola Lata', N'Guaraná lata', N'guarita lata', N'Fanta laranja lata', N'Fanta uva lata');
  IF v_n > 0 THEN
    RAISE_APPLICATION_ERROR(-20003, 'Ha ' || v_n || ' produto(s) fora da lista em tb_produto. Nada foi alterado.');
  END IF;

  -- 2. id novo de cada nome = a posicao dele na lista
  FOR i IN 1 .. v_nomes.COUNT LOOP
    SELECT COUNT(*) INTO v_n FROM "PIM"."tb_produto" WHERE "descricao_produto" = v_nomes(i);
    IF v_n <> 1 THEN
      RAISE_APPLICATION_ERROR(-20004, 'Produto nao encontrado (ou repetido) em tb_produto: ' || v_nomes(i));
    END IF;
    SELECT "id_produto" INTO v_old FROM "PIM"."tb_produto" WHERE "descricao_produto" = v_nomes(i);
    v_case := v_case || ' WHEN ' || v_old || ' THEN ' || i;
  END LOOP;

  -- 3. tabelas que apontam para tb_produto
  SELECT constraint_name INTO v_pk FROM user_constraints
   WHERE table_name = 'tb_produto' AND constraint_type = 'P';
  SELECT c.table_name, c.constraint_name, cc.column_name
    BULK COLLECT INTO v_tab, v_cons, v_col
    FROM user_constraints c
    JOIN user_cons_columns cc ON cc.constraint_name = c.constraint_name
   WHERE c.constraint_type = 'R' AND c.r_constraint_name = v_pk;

  -- id pode ser alterado na mao
  EXECUTE IMMEDIATE 'ALTER TABLE "PIM"."tb_produto" MODIFY ("id_produto" GENERATED BY DEFAULT ON NULL AS IDENTITY)';

  -- 4. desliga as chaves estrangeiras, troca os ids e liga de novo
  FOR i IN 1 .. v_cons.COUNT LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE "PIM"."' || v_tab(i) || '" DISABLE CONSTRAINT "' || v_cons(i) || '"';
  END LOOP;
  v_off := TRUE;

  FOR i IN 1 .. v_cons.COUNT LOOP
    EXECUTE IMMEDIATE 'UPDATE "PIM"."' || v_tab(i) || '" SET "' || v_col(i) || '" = CASE "' || v_col(i) || '"' || v_case
                      || ' ELSE "' || v_col(i) || '" END';
    DBMS_OUTPUT.PUT_LINE(v_tab(i) || ': ' || SQL%ROWCOUNT || ' linha(s) atualizada(s)');
  END LOOP;
  EXECUTE IMMEDIATE 'UPDATE "PIM"."tb_produto" SET "id_produto" = CASE "id_produto"' || v_case || ' ELSE "id_produto" END';
  COMMIT;

  religa;

  -- 5. o contador passa a comecar logo depois do maior id
  EXECUTE IMMEDIATE 'ALTER TABLE "PIM"."tb_produto" MODIFY ("id_produto" GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE))';
  DBMS_OUTPUT.PUT_LINE('ok: produtos renumerados de 1 a 5; proximo id = 6');
EXCEPTION WHEN OTHERS THEN
  ROLLBACK;
  IF v_off THEN religa; END IF;
  RAISE;
END;
/

SELECT "id_produto", "descricao_produto", "qdte_produto" FROM "PIM"."tb_produto" ORDER BY 1;
SELECT "id_produto", COUNT(*) AS itens_de_venda FROM "PIM"."tb_item_venda" GROUP BY "id_produto" ORDER BY 1;
